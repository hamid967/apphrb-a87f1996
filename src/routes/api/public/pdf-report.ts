type SigPos = "top" | "bottom";
type SigAlign = "start" | "center" | "end";
type SigLayout = { position: SigPos; offset: number; align: SigAlign };
const SIG_LAYOUT_DEFAULTS: Record<Template, SigLayout> = {
  classic: { position: "bottom", offset: 26, align: "start" },
  modern: { position: "bottom", offset: 26, align: "start" },
  minimal: { position: "bottom", offset: 26, align: "center" },
};

async function loadBrandingSettings() {
  try {
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
    const { data } = await supabaseAdmin
      .from("app_settings")
      .select("key,value")
      .in("key", [
        "report.company_name",
        "report.phone",
        "report.email",
        "report.website",
        "report.sig_layout",
        "report.contact_in_header",
        "report.company_id",
        "report.use_company_settings",
      ]);
    const m = new Map((data ?? []).map((r: any) => [r.key, r.value as string]));
    let layout = SIG_LAYOUT_DEFAULTS;
    try {
      const raw = m.get("report.sig_layout");
      if (raw) layout = { ...SIG_LAYOUT_DEFAULTS, ...JSON.parse(raw) };
    } catch {}
    let company = m.get("report.company_name") || SIGNATURE_DEFAULTS.company;
    let phone = m.get("report.phone") || SIGNATURE_DEFAULTS.phone;
    let email = m.get("report.email") || SIGNATURE_DEFAULTS.email;
    const website = m.get("report.website") || SIGNATURE_DEFAULTS.website;

    // Data source: linked Company Settings row (public.companies) overrides
    // the free-text signature fields when enabled.
    const useCompany = (m.get("report.use_company_settings") ?? "false") === "true";
    const linkedCompanyId = m.get("report.company_id") || null;
    let sourceCompanyId: string | null = null;
    if (useCompany && linkedCompanyId) {
      const { data: co } = await supabaseAdmin
        .from("companies")
        .select("id,name,phone,email")
        .eq("id", linkedCompanyId)
        .is("deleted_at", null)
        .maybeSingle();
      if (co) {
        sourceCompanyId = co.id;
        if (co.name) company = co.name;
        if (co.phone) phone = co.phone;
        if (co.email) email = co.email;
      }
    }

    return {
      company,
      phone,
      email,
      website,
      layout,
      contactInHeader: (m.get("report.contact_in_header") ?? "false") === "true",
      sourceCompanyId,
    };
  } catch {
    return {
      ...SIGNATURE_DEFAULTS,
      layout: SIG_LAYOUT_DEFAULTS,
      contactInHeader: false,
      sourceCompanyId: null,
    };
  }
}

